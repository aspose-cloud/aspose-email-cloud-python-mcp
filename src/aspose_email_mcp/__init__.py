"""`aspose-email-mcp` — Email's curated 47-tool MCP surface (Sprint 12 seed, 2 tools; Sprint 13
Phase 2 generalizer, 45 more — PRD Section 2.6/FR15b, `docs/DECISION_LOG.md` Decision 4).

A genuinely separate, installable, versioned package (zero import dependency on the builder's own
`mcp_builder`). No core/extra split (Fork 4 precedent) — Email is not a shared dependency of any
other product, so all curated tools live here.

Declares a real, ordinary versioned dependency on `aspose-storage-core-mcp` (`pyproject.toml`) for
the bundled core subset (FR15b). `generated/email/server.py` is where that bundling actually
happens; this package only owns Email's own tools.

**Sprint 12's original 2 operations are real local-file shapes** — `email_convert_file` (transform)
and `email_extract_properties` (upload-shape, returns parsed `EmailDto` fields instead of a file) both
read a local `.eml`/`.msg`/etc. file directly, no Cloud Storage round trip.

**Sprint 13 Phase 2 adds 45 more, all zero-hand-authored operation mappings** — the Codegen
generalizer (`mcp_builder.codegen.generalizer`) classified them from Email's real, live-fetched
`v4.0` spec (`ir/email/generalized_operations.json` has the full disclosed record, including 47
operations it correctly flagged rather than guessed). Covers calendar/contact/MAPI document
read/convert operations, disposable-email/AI name-parsing utilities (no storage or account setup
needed), Email's own dedicated storage-file/folder CRUD surface, and IMAP/EWS-style mail-client
operations (`email_*_client_*`) that need a real configured mail account to exercise, not just
Aspose Cloud credentials — only a representative sample requiring no such account was live-verified
this sprint (see the Sprint 13 execution plan §6 for exactly which).

Regenerated by the builder's Codegen agent (`mcp_builder.codegen`) from the tracked Email IR — never
hand-patched (rubric gate 8).
"""

